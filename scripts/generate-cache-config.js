#!/usr/bin/env node
/**
 * Cache Optimization Script
 * 
 * This script generates cache configuration for different types of assets,
 * optimizing cache policy for improved performance.
 */

const fs = require('fs');
const path = require('path');

// Cache configuration for different asset types
const cacheConfig = {
  // Static assets that rarely change
  static: {
    assets: [
      { ext: ['woff', 'woff2', 'ttf', 'otf'], dir: 'fonts' },
      { ext: ['ico', 'webmanifest'], dir: '' },
      { ext: ['webp', 'png', 'jpg', 'jpeg', 'gif', 'svg'], dir: 'icons' },
    ],
    headers: [
      { key: 'Cache-Control', value: 'public, max-age=31536000, immutable' }
    ]
  },
  // Assets that may change occasionally
  dynamic: {
    assets: [
      { ext: ['webp', 'png', 'jpg', 'jpeg', 'gif', 'svg'], dir: 'images' },
      { ext: ['webp', 'png', 'jpg', 'jpeg', 'gif', 'svg'], dir: 'blog' },
    ],
    headers: [
      { key: 'Cache-Control', value: 'public, max-age=86400, stale-while-revalidate=31536000' }
    ]
  },
  // JavaScript and CSS files
  code: {
    assets: [
      { ext: ['js'], dir: '_next/static' },
      { ext: ['css'], dir: '_next/static' },
    ],
    headers: [
      { key: 'Cache-Control', value: 'public, max-age=31536000, immutable' }
    ]
  },
  // HTML and data files
  html: {
    assets: [
      { ext: ['html'], dir: '' },
      { ext: ['json'], dir: '_next/data' },
    ],
    headers: [
      { key: 'Cache-Control', value: 'public, max-age=0, must-revalidate' }
    ]
  }
};

// Generate Next.js headers configuration
function generateHeadersConfig() {
  let config = [];

  Object.entries(cacheConfig).forEach(([type, { assets, headers }]) => {
    assets.forEach(({ ext, dir }) => {
      ext.forEach(extension => {
        const source = dir 
          ? `/${dir}/:path*.${extension}`
          : `/:path*.${extension}`;
        
        config.push({
          source,
          headers: [...headers]
        });
      });
    });
  });

  return config;
}

// Generate the next.config.js snippet
function generateNextConfigSnippet() {
  const headers = generateHeadersConfig();
  const configSnippet = `
/**
 * Cache optimization configuration
 * Auto-generated by scripts/generate-cache-config.js
 */

// Headers configuration for optimal caching
const cacheHeaders = ${JSON.stringify(headers, null, 2)};

// Add this to your next.config.js:
// 
// async headers() {
//   return cacheHeaders;
// },
`;

  return configSnippet;
}

// Write the configuration file
function writeConfigFile() {
  const configSnippet = generateNextConfigSnippet();
  const outputPath = path.resolve(process.cwd(), 'cache-config.js');
  
  fs.writeFileSync(outputPath, configSnippet);
  console.log(`✅ Cache configuration generated at: ${outputPath}`);
  
  // Display next steps
  console.log(`
🔍 Next steps:
1. Open next.config.js
2. Import the cache configuration:
   const cacheHeaders = require('./cache-config').cacheHeaders;
3. Add the headers function to your module.exports:
   async headers() {
     return cacheHeaders;
   },
`);
}

// Main function
function main() {
  console.log('⚙️ Generating optimal cache configuration...');
  writeConfigFile();
  console.log('✨ Cache optimization complete!');
}

main(); 